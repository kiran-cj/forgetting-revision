"""Keeps the README's results section in step with the code.

The Results section of README.md is generated by the checker. If a change to
the postulates, claims or operators alters the results and nobody reruns
`uv run check-postulates --update-readme`, the first test here fails and says
so. Generated docs that can silently go stale are worse than none.
"""

import re
from pathlib import Path

import pytest

from forgetting_revision.checker import (
    README_END,
    README_START,
    format_markdown,
    main,
    replace_between_markers,
    update_readme,
)
from forgetting_revision.claims import run_claims

README = Path(__file__).resolve().parents[2] / "README.md"


@pytest.fixture(scope="module")
def markdown(reports2, transform_reports2):
    return format_markdown(reports2, transform_reports2, run_claims())


def test_readme_results_are_up_to_date(markdown):
    text = README.read_text(encoding="utf-8")
    assert replace_between_markers(text, markdown) == text, (
        "README.md is out of date: run `uv run check-postulates --update-readme`"
    )


def test_markdown_contents(markdown):
    assert markdown.startswith("Checked exhaustively over 2 variables (p, q)")
    assert "| 2 | Success | AGM K\\*2 | ✓ | ✗ (1,050 fail) | ✗ (225 fail) |" in markdown
    assert "✓ (vacuous)" in markdown
    assert "**All verdicts match" in markdown


def test_pipes_inside_cells_are_escaped(markdown):
    """i5's detail contains a partition written with |, which would split the cell."""
    row = next(line for line in markdown.splitlines() if line.startswith("| i5 |"))
    assert "{TT, FF} \\| {TF, FT}" in row
    cells = re.split(r"(?<!\\)\|", row)[1:-1]     # split on | not preceded by a backslash
    assert len(cells) == 5                          # #, Claim, Source, Result, Detail


# ------------------------------------------------------------ marker handling

def test_only_the_marked_region_changes():
    text = f"intro\n{README_START}\nold table\n{README_END}\noutro\n"
    new = replace_between_markers(text, "new table")
    assert new == f"intro\n{README_START}\nnew table\n{README_END}\noutro\n"
    assert replace_between_markers(new, "new table") == new          # idempotent


@pytest.mark.parametrize("text", [
    "no markers at all",
    f"{README_START} only the start",
    f"{README_END} before {README_START}",
], ids=["none", "start only", "reversed"])
def test_bad_markers_are_an_error(text):
    with pytest.raises(ValueError, match="README needs"):
        replace_between_markers(text, "table")


def test_update_readme_reports_whether_it_changed(tmp_path):
    path = tmp_path / "README.md"
    path.write_text(f"# Title\n{README_START}\n{README_END}\n", encoding="utf-8")
    assert update_readme(path, "table") is True
    assert update_readme(path, "table") is False
    assert "table" in path.read_text(encoding="utf-8")


# ------------------------------------------------------------ command line

def test_markdown_flag_prints_tables(capsys):
    assert main(["--vars", "1", "--markdown"]) == 0
    assert "#### Postulates" in capsys.readouterr().out


def test_update_readme_refuses_other_signatures():
    with pytest.raises(SystemExit):
        main(["--vars", "1", "--update-readme"])
